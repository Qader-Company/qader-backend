<?php

namespace App\Modules\V1\Authentication\Presentation\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class UpdateDeviceTokenRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    public function rules(): array
    {
        return [
            'fcm_token' => ['required', 'string', 'max:4096'],
            'platform' => ['required', Rule::in(['web', 'ios', 'android'])],
        ];
    }

    public function bodyParameters(): array
    {
        return [
            'fcm_token' => [
                'description' => 'The latest FCM registration token generated by this app installation.',
                'example' => 'fcm-registration-token-from-the-device',
            ],
            'platform' => [
                'description' => 'The platform that generated the token.',
                'example' => 'android',
            ],
        ];
    }
}
